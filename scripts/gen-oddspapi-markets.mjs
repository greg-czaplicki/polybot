#!/usr/bin/env node
// Regenerates src/server/pipeline/oddspapi-markets.ts — the compact OddsPapi
// market catalog the Pinnacle adapter needs to tell full-game totals apart
// from corners/bookings/sets (OddsPapi merges those into one fixture with
// Pinnacle-native ids that look identical).
//
//   ODDSPAPI_KEY=... node scripts/gen-oddspapi-markets.mjs          (1 billable request)
//   node scripts/gen-oddspapi-markets.mjs path/to/markets.json      (offline)
//
// Re-run when a new total line shows up that the catalog lacks (the sweep
// logs `unknown totals market` counts); unknown ids are skipped, never guessed.
import { readFileSync, writeFileSync } from "node:fs";

const OUT = new URL("../src/server/pipeline/oddspapi-markets.ts", import.meta.url);
// Winner market per OddsPapi sport id. Soccer = 90-minute 1X2 (101);
// US sports/tennis = "Winner (incl. overtime/extra innings)" = the
// Polymarket settlement basis.
const H2H = { 10: 101, 11: 111, 12: 121, 13: 131, 14: 141, 15: 151 };
// Totals family per sport: soccer 90-minute goals; US sports incl. OT;
// tennis GAMES (not sets — Polymarket tennis totals are games).
const FAMILY = {
	10: ["totals", "fulltime"],
	11: ["totals", "result"],
	12: ["totals-games", "result"],
	13: ["totals", "result"],
	14: ["totals", "result"],
	15: ["totals", "result"],
};

async function load() {
	const arg = process.argv[2];
	if (arg) return JSON.parse(readFileSync(arg, "utf8"));
	const key = process.env.ODDSPAPI_KEY;
	if (!key) throw new Error("ODDSPAPI_KEY unset and no markets.json path given");
	const res = await fetch(`https://api.oddspapi.io/v4/markets?apiKey=${key}`);
	if (!res.ok) throw new Error(`/v4/markets ${res.status}`);
	return await res.json();
}

const markets = await load();
const totals = {};
for (const m of markets) {
	const fam = FAMILY[m.sportId];
	if (!fam || m.playerProp) continue;
	if (m.marketType !== fam[0] || m.period !== fam[1]) continue;
	if (typeof m.handicap !== "number") continue;
	totals[m.marketId] = [m.sportId, m.handicap];
}
for (const [sport, id] of Object.entries(H2H)) {
	const m = markets.find((x) => x.marketId === id);
	if (!m || m.sportId !== Number(sport))
		throw new Error(`h2h market ${id} missing or wrong sport in catalog`);
}
const ids = Object.keys(totals).map(Number).sort((a, b) => a - b);
const lines = ids.map((id) => `\t${id}: [${totals[id][0]}, ${totals[id][1]}],`);
const src = `// GENERATED by scripts/gen-oddspapi-markets.mjs — do not edit by hand.
// Compact OddsPapi market catalog (/v4/markets) for the Pinnacle adapter.
// Generated ${new Date().toISOString().slice(0, 10)} from ${markets.length} catalog rows.

/** OddsPapi sport id → winner market id (soccer 1X2 fulltime, others incl. OT). */
export const ODDSPAPI_H2H_MARKET: Record<number, number> = ${JSON.stringify(H2H, null, "\t")};

/** OddsPapi totals-ladder market id → [sport id, line]. Soccer = fulltime
 * goals, US sports = incl. OT, tennis = games. Ids absent here are NOT
 * full-game totals (corners, bookings, sets, periods, team totals). */
export const ODDSPAPI_TOTALS_MARKET: Record<number, [number, number]> = {
${lines.join("\n")}
};
`;
writeFileSync(OUT, src);
console.log(`wrote ${ids.length} totals markets + ${Object.keys(H2H).length} h2h markets → ${OUT.pathname}`);
